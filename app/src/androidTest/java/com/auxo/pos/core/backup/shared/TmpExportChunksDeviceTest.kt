/** TEMPORARY: reports Android's re-export of the rich web file, gzipped and in pieces, through failure messages. */
@RunWith(AndroidJUnit4::class)
class TmpExportChunksDeviceTest {
    companion object {
        val text: String by lazy {
            val context: Context = ApplicationProvider.getApplicationContext()
            context.deleteDatabase("tmp-chunks.db")
            val bytes = InstrumentationRegistry.getInstrumentation().context.assets.open("shared/web-rich.auxoshared").use { it.readBytes() }
            val doc = SharedBackupFile.open(bytes, "long shared phrase 91")
            val store = com.auxo.pos.core.photos.FileProductPhotoStore(context)
            val db = AuxoDatabase.builder(context, "tmp-chunks.db").build()
            try {
                runBlocking {
                    SharedRestoreApplier(db, photos = store, workDir = context.cacheDir).apply(SharedRestorePlanner.plan(doc))
                    val file = SharedExport(db.sharedExportDao(), photoFile = { n -> store.files().firstOrNull { it.name == n } })
                        .encrypt("long shared phrase 91", 1_700_000_000_000L, "android-test")
                    java.util.Base64.getEncoder().encodeToString(file)
                }
            } finally {
                db.close()
                context.deleteDatabase("tmp-chunks.db")
            }
        }
    }

